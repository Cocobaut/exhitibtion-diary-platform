-- 0. KÍCH HOẠT EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "pgcrypto";
CREATE EXTENSION IF NOT EXISTS "unaccent";

-- Hàm trigger tự động cập nhật timestamp updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE 'plpgsql';

-- ====================================================================
-- 1. BẢNG: users (Quản lý tài khoản & người dùng)
-- ====================================================================
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN', 'OWNER')),
    avatar_url TEXT NULL,
    bio VARCHAR(255) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_id_role UNIQUE (id, role)
);

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ====================================================================
-- 2. BẢNG: rooms (3 Phòng triển lãm)
-- ====================================================================
CREATE TABLE IF NOT EXISTS rooms (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(20) NOT NULL UNIQUE,
    title VARCHAR(100) NOT NULL,
    description TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- 3. BẢNG: artworks (Tác phẩm & Bài đăng trong 3 phòng triển lãm)
-- ====================================================================
CREATE TABLE IF NOT EXISTS artworks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    room_id SMALLINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    original_language VARCHAR(5) NOT NULL DEFAULT 'vi' CHECK (original_language IN ('vi', 'en')),
    title VARCHAR(150) NOT NULL,
    title_vi VARCHAR(150) NULL,
    title_en VARCHAR(150) NULL,
    author_display_name VARCHAR(50) NULL,
    is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    short_content TEXT NOT NULL,
    short_content_vi TEXT NULL,
    short_content_en TEXT NULL,
    content TEXT NOT NULL,
    content_vi TEXT NULL,
    content_en TEXT NULL,
    media_url TEXT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' 
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED', 'PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by UUID NULL REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ NULL,
    admin_note TEXT NULL,
    target_date TIMESTAMPTZ NULL,
    is_opened BOOLEAN NOT NULL DEFAULT FALSE,
    visibility VARCHAR(10) NOT NULL DEFAULT 'PUBLIC' 
        CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    tag_category VARCHAR(30) NULL,
    color_code VARCHAR(10) NULL,
    view_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_artworks_updated_at
BEFORE UPDATE ON artworks
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ====================================================================
-- 4. BẢNG: artwork_interactions (Tương tác cảm xúc trên tác phẩm)
-- ====================================================================
CREATE TABLE IF NOT EXISTS artwork_interactions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    artwork_id UUID NOT NULL REFERENCES artworks(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reaction_type VARCHAR(20) NOT NULL 
        CHECK (reaction_type IN ('HUG', 'HEART', 'SYMPATHY', 'INSPIRED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_artwork_user_reaction UNIQUE (artwork_id, user_id, reaction_type)
);

-- ====================================================================
-- 5. BẢNG: diaries (Nhật ký cá nhân)
-- ====================================================================
CREATE TABLE IF NOT EXISTS diaries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    original_language VARCHAR(5) NOT NULL DEFAULT 'vi' CHECK (original_language IN ('vi', 'en')),
    title VARCHAR(150) NULL,
    title_vi VARCHAR(150) NULL,
    title_en VARCHAR(150) NULL,
    content TEXT NOT NULL,
    content_vi TEXT NULL,
    content_en TEXT NULL,
    mood VARCHAR(30) NULL,
    media_urls JSONB NULL DEFAULT '[]'::jsonb,
    is_encrypted BOOLEAN NOT NULL DEFAULT FALSE,
    is_public BOOLEAN NOT NULL DEFAULT FALSE,
    is_approved BOOLEAN NOT NULL DEFAULT TRUE,
    entry_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_diaries_updated_at
BEFORE UPDATE ON diaries
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ====================================================================
-- 6. BẢNG: diary_interactions (Tương tác trên nhật ký cộng đồng)
-- ====================================================================
CREATE TABLE IF NOT EXISTS diary_interactions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    diary_id UUID NOT NULL REFERENCES diaries(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reaction_type VARCHAR(20) NOT NULL 
        CHECK (reaction_type IN ('HEART', 'HUG', 'SYMPATHY')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_diary_user_reaction UNIQUE (diary_id, user_id)
);

-- ====================================================================
-- 7. BẢNG: message_capsules (Kho thông điệp Máy nhả thông điệp)
-- ====================================================================
CREATE TABLE IF NOT EXISTS message_capsules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id UUID NULL,
    author_role VARCHAR(20) NULL DEFAULT 'ADMIN' 
        CHECK (author_role IN ('ADMIN', 'OWNER') OR author_role IS NULL),
    message TEXT NOT NULL,
    message_vi TEXT NOT NULL DEFAULT '',
    message_en TEXT NOT NULL DEFAULT '',
    category VARCHAR(30) NOT NULL DEFAULT 'HEALING' 
        CHECK (category IN ('HEALING', 'COURAGE', 'PERSPECTIVE')),
    is_approved BOOLEAN NOT NULL DEFAULT TRUE,
    draw_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_message_capsules_author FOREIGN KEY (author_id, author_role) 
        REFERENCES users(id, role) ON DELETE SET NULL
);

CREATE TRIGGER trg_message_capsules_updated_at
BEFORE UPDATE ON message_capsules
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ====================================================================
-- 8. BẢNG: user_capsule_draws (Lịch sử rút thông điệp của người dùng)
-- ====================================================================
CREATE TABLE IF NOT EXISTS user_capsule_draws (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    capsule_id BIGINT NOT NULL REFERENCES message_capsules(id) ON DELETE CASCADE,
    is_saved BOOLEAN NOT NULL DEFAULT FALSE,
    drawn_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- 9. BẢNG: notifications (Hộp tin nhắn / Thông báo)
-- ====================================================================
CREATE TABLE IF NOT EXISTS notifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    recipient_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_id UUID NULL REFERENCES users(id) ON DELETE SET NULL,
    type VARCHAR(30) NOT NULL 
        CHECK (type IN ('INTERACTION', 'CAPSULE', 'SYSTEM', 'REMINDER')),
    title VARCHAR(150) NOT NULL,
    body TEXT NOT NULL,
    target_url VARCHAR(255) NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- 10. BẢNG: password_reset_tokens (Token đặt lại mật khẩu)
-- ====================================================================
CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- 11. BẢNG: revoked_tokens (Thu hồi JWT Token khi Logout)
-- ====================================================================
CREATE TABLE IF NOT EXISTS revoked_tokens (
    jti VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- 12. BẢNG: admin_audit_logs (Nhật ký quản trị của Admin)
-- ====================================================================
CREATE TABLE IF NOT EXISTS admin_audit_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    artwork_id UUID NULL REFERENCES artworks(id) ON DELETE SET NULL,
    artwork_title VARCHAR(150) NOT NULL,
    room_id SMALLINT NOT NULL REFERENCES rooms(id),
    admin_id UUID NULL REFERENCES users(id) ON DELETE SET NULL,
    action_type VARCHAR(40) NOT NULL CHECK (action_type IN 
        ('CREATE_DIRECT', 'UPDATE', 'APPROVE', 'APPROVE_AND_UPLOAD_MEDIA', 'REJECT', 'ARCHIVE',
         'REQUEST_DELETE_USER', 'ACTIVATE_USER', 'DEACTIVATE_USER', 'BLOCK_USER', 'UNBLOCK_USER',
         'DELETE_USER', 'UPDATE_USER_ROLE')),
    note TEXT NULL,
    performed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ====================================================================
-- 13. CÁC INDEXES TỐI ƯU TRUY VẤN
-- ====================================================================
CREATE INDEX IF NOT EXISTS idx_artworks_room_user 
    ON artworks (room_id, user_id);

CREATE INDEX IF NOT EXISTS idx_artworks_fts 
    ON artworks USING GIN (to_tsvector('simple', 
        coalesce(title, '') || ' ' || 
        coalesce(title_vi, '') || ' ' || 
        coalesce(title_en, '') || ' ' || 
        coalesce(short_content, '') || ' ' || 
        coalesce(short_content_vi, '') || ' ' || 
        coalesce(short_content_en, '') || ' ' || 
        coalesce(content, '') || ' ' || 
        coalesce(content_vi, '') || ' ' || 
        coalesce(content_en, '') || ' ' || 
        coalesce(author_display_name, '')
    ));

CREATE INDEX IF NOT EXISTS idx_diaries_fts 
    ON diaries USING GIN (to_tsvector('simple', 
        coalesce(title, '') || ' ' || 
        coalesce(title_vi, '') || ' ' || 
        coalesce(title_en, '') || ' ' || 
        coalesce(content, '') || ' ' || 
        coalesce(content_vi, '') || ' ' || 
        coalesce(content_en, '')
    ));

CREATE INDEX IF NOT EXISTS idx_notifications_recipient_unread 
    ON notifications (recipient_id) 
    WHERE is_read = FALSE;

CREATE INDEX IF NOT EXISTS idx_diaries_user_entry_date 
    ON diaries (user_id, entry_date);

CREATE INDEX IF NOT EXISTS idx_capsules_approved_category 
    ON message_capsules (is_approved, category);

CREATE INDEX IF NOT EXISTS idx_audit_logs_filter 
    ON admin_audit_logs (room_id, admin_id, action_type, performed_at DESC);
